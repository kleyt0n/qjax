# --------------------------------------------------------------------------- #
# The physically generated label noise, and the labels a perfect model would use
# --------------------------------------------------------------------------- #
def order_parameter_reference(configurations: jnp.ndarray, temperatures: jnp.ndarray):
    """Best ``|m|``-threshold classifier: its threshold, its per-``T`` error, its labels.

    The magnetization is the exact order parameter, so a threshold on ``|m|`` is
    the best any function of the configuration can do at separating the phases.
    Two things follow, and they are the two ingredients of this example:

    - Where the threshold classifier disagrees with the temperature label, the
      *label* is what is wrong. Its per-temperature error rate ``eta_eff(T, L)``
      is therefore a measurement of the physically generated label noise, and it
      plays the role that the injected ``eta`` plays in
      ``examples/classification.py``.
    - Its own labels are the closest thing to ground truth available, so scoring
      a network against them is the analogue of a *clean* test set. Scoring
      against the temperature labels instead rewards fitting the noise, which is
      exactly what the unbounded loss does.

    Args:
        configurations: Samples of shape ``(T, S, L, L)``.
        temperatures: The temperature grid, shape ``(T,)``.

    Returns:
        ``(threshold, noise, labels)`` with ``noise`` of shape ``(T,)`` and
        ``labels`` of shape ``(T, S)``.
    """
    absolute = jnp.abs(qp.ising_magnetization(configurations))
    ordered = (temperatures < qp.ISING_TC)[:, None]

    candidates = jnp.linspace(0.0, 1.0, 201)[:, None, None]
    pooled = jnp.mean((absolute[None, :, :] > candidates) != ordered[None, :, :], axis=(1, 2))
    threshold = candidates[jnp.argmin(pooled), 0, 0]

    predicted = absolute > threshold
    return threshold, jnp.mean(predicted != ordered, axis=-1), predicted.astype(jnp.int32)


# --------------------------------------------------------------------------- #
# The classifier
# --------------------------------------------------------------------------- #
def init_params(key: jax.Array, num_sites: int) -> dict:
    """Initialize a ``num_sites -> HIDDEN -> 2`` MLP, plus the learnable ``q_raw``."""
    k1, k2, k3 = jax.random.split(key, 3)
    h1, h2 = HIDDEN
    return {
        "w1": jax.random.normal(k1, (num_sites, h1)) * jnp.sqrt(2.0 / num_sites),
        "b1": jnp.zeros(h1),
        "w2": jax.random.normal(k2, (h1, h2)) * jnp.sqrt(2.0 / h1),
        "b2": jnp.zeros(h2),
        "w3": jax.random.normal(k3, (h2, 2)) * jnp.sqrt(2.0 / h2),
        "b3": jnp.zeros(2),
        "q_raw": jnp.array(Q_RAW_INIT),
    }


def logits(params: dict, x: jnp.ndarray) -> jnp.ndarray:
    """Forward pass returning two logits: [disordered, ordered]."""
    h = jnp.tanh(x @ params["w1"] + params["b1"])
    h = jnp.tanh(h @ params["w2"] + params["b2"])
    return h @ params["w3"] + params["b3"]


def resolve_q(params: dict, q_fixed: float, is_learnable: bool):
    """The entropic index in use: a constant, or the bounded learnable one."""
    return bounded_q(params["q_raw"], Q_MIN, Q_MAX) if is_learnable else q_fixed


@partial(jax.jit, static_argnames=("is_learnable", "steps"))
def train(params: dict, x, y_onehot, q_fixed, is_learnable: bool, steps: int):
    """Full-batch Adam on the Tsallis cross-entropy; returns params and the q trace.

    ``normalizer_q=1.0`` keeps an ordinary softmax under the deformed loss. That
    is deliberate twice over: it avoids the 50-step entmax bisection in the inner
    loop, and it rules out the ``+inf`` the loss docstring warns about, where a
    sparse normalizer puts exactly zero mass on the true class.
    """
    b1, b2, eps = 0.9, 0.999, 1e-8
    m = jax.tree_util.tree_map(jnp.zeros_like, params)
    v = jax.tree_util.tree_map(jnp.zeros_like, params)

    def loss_fn(p):
        q = resolve_q(p, q_fixed, is_learnable)
        return tsallis_cross_entropy_loss(
            logits(p, x), y_onehot, q=q, from_logits=True, normalizer_q=1.0
        )

    def step(carry, t):
        p, m, v = carry
        grads = jax.grad(loss_fn)(p)
        m = jax.tree_util.tree_map(lambda m, g: b1 * m + (1 - b1) * g, m, grads)
        v = jax.tree_util.tree_map(lambda v, g: b2 * v + (1 - b2) * g * g, v, grads)
        bc1, bc2 = 1 - b1 ** (t + 1), 1 - b2 ** (t + 1)
        p = jax.tree_util.tree_map(
            lambda p, m, v: p - LR * (m / bc1) / (jnp.sqrt(v / bc2) + eps), p, m, v
        )
        return (p, m, v), resolve_q(p, q_fixed, is_learnable)

    (params, _, _), trace = jax.lax.scan(step, (params, m, v), jnp.arange(steps))
    return params, trace


def flatten_symmetrized(configurations: jnp.ndarray, labels: jnp.ndarray):
    """Flatten to ``(N, L*L)`` and append the global spin flip of every sample.

    Not data augmentation for its own sake: ``-s`` has exactly the same energy as
    ``s``, so without it the network can key on ``sign(m)``, which carries no
    phase information at all.
    """
    x = configurations.reshape(-1, configurations.shape[-1] * configurations.shape[-2])
    y = labels.reshape(-1)
    return jnp.concatenate([x, -x]), jnp.concatenate([y, y])


def temperature_labels(temperatures: jnp.ndarray, samples: int, boundary: float) -> jnp.ndarray:
    """``1[T < boundary]``, broadcast to one label per sample."""
    return jnp.repeat((temperatures < boundary).astype(jnp.int32)[:, None], samples, axis=1)


def balanced_accuracy(predicted: jnp.ndarray, targets: jnp.ndarray) -> float:
    """Mean of the two per-class recalls.

    Plain accuracy is the wrong metric for the confusion scan: a proposed
    boundary near the edge of the temperature grid puts almost every sample in
    one class, and a constant predictor then scores close to 1. That trivial rise
    is what produces the outer arms of the W and can swamp the real peak.
    Averaging the per-class recalls pins an uninformative boundary at 0.5, so the
    only way to score well is to separate two populations that genuinely differ.
    """
    recalls = [
        jnp.mean(predicted[targets == label] == label)
        for label in (0, 1)
        if int(jnp.sum(targets == label)) > 0
    ]
    return float(jnp.mean(jnp.stack(recalls)))


def _windowed(temperatures: jnp.ndarray, curve: jnp.ndarray):
    """Restrict a curve to `CRITICAL_WINDOW`, where the temperature grid is dense."""
    inside = (temperatures >= CRITICAL_WINDOW[0]) & (temperatures <= CRITICAL_WINDOW[1])
    return temperatures[inside], curve[inside]


def ordered_probability(params: dict, configurations: jnp.ndarray):
    """Mean ``P(ordered)`` and mean output Tsallis entropy at each temperature.

    The entropy is evaluated at ``q = 2`` -- the Gini/collision index, whose
    ``q -> 1`` limit is the Shannon entropy. It peaks where the network is
    maximally undecided, so its maximum is a pseudo-critical temperature obtained
    *without* reference to ``T_c``.
    """
    flat = configurations.reshape(*configurations.shape[:2], -1)
    symmetric = jnp.concatenate([flat, -flat], axis=1)
    probabilities = jax.nn.softmax(logits(params, symmetric), axis=-1)
    entropy = qjax.tsallis_entropy(probabilities, q=2.0, axis=-1)
    return jnp.mean(probabilities[..., 1], axis=-1), jnp.mean(entropy, axis=-1)


def crossover_width(temperatures: jnp.ndarray, probability: jnp.ndarray) -> jnp.ndarray:
    r"""Temperature interval over which ``P(ordered)`` falls from 3/4 to 1/4.

    This is the width of the region the classifier cannot decide, so it is set by
    where ``xi`` exceeds ``L`` and scales as ``L^{-1/nu}``. Reading ``nu`` off it
    is the cleanest exponent measurement in the pipeline -- and, unlike the
    ``T_c`` estimates, it needs no extrapolation.
    """
    upper = qp.crossing_temperature(temperatures, probability, 0.25)
    lower = qp.crossing_temperature(temperatures, probability, 0.75)
    return upper - lower


# --------------------------------------------------------------------------- #
# Experiment
# --------------------------------------------------------------------------- #
def run(config: dict) -> dict:
    """Sample, train every arm at every lattice size, and collect the estimates."""
    temperatures = config["temperatures"]
    sizes = config["sizes"]
    per_temperature = config["samples_per_temperature"]
    split = per_temperature - per_temperature // 2

    results: dict = {"temperatures": np.asarray(temperatures), "sizes": sizes, "showcase": {}}
    for field in (
        "noise",
        "bayes_error",
        "magnetization",
        "energy",
        "binder",
        "probability",
        "entropy",
        "width",
        "accuracy_temperature",
        "accuracy_order",
        "q_trace",
    ):
        results[field] = {}

    for size in sizes:
        print(f"  L = {size}: sampling", flush=True)
        configurations = qp.sample_ising(
            jax.random.PRNGKey(1000 + size),
            size,
            temperatures,
            per_temperature,
            config["equilibration"][size],
        )
        magnetization = qp.ising_magnetization(configurations)
        threshold, noise, clean_labels = order_parameter_reference(configurations, temperatures)

        results["magnetization"][size] = np.asarray(jnp.mean(jnp.abs(magnetization), axis=-1))
        results["energy"][size] = np.asarray(
            jnp.mean(qp.ising_energy(configurations), axis=-1) / size**2
        )
        results["binder"][size] = np.asarray(qp.binder_cumulant(magnetization, axis=-1))
        results["noise"][size] = np.asarray(noise)
        results["bayes_error"][size] = float(jnp.mean(noise))

        train_x, train_y = flatten_symmetrized(
            configurations[:, :split],
            temperature_labels(temperatures, split, qp.ISING_TC),
        )
        test_x, test_temperature = flatten_symmetrized(
            configurations[:, split:],
            temperature_labels(temperatures, per_temperature - split, qp.ISING_TC),
        )
        _, test_order = flatten_symmetrized(configurations[:, split:], clean_labels[:, split:])
        one_hot = jax.nn.one_hot(train_y, 2)

        for label, q_fixed, learnable in METHODS:
            gathered: dict[str, list] = {
                k: [] for k in ("prob", "entropy", "width", "temp", "order", "trace")
            }
            for seed in config["seeds"]:
                start = init_params(jax.random.PRNGKey(seed), size**2)
                trained, trace = train(start, train_x, one_hot, q_fixed, learnable, config["steps"])
                probability, entropy = ordered_probability(trained, configurations[:, split:])
                predicted = jnp.argmax(logits(trained, test_x), axis=-1)
                gathered["prob"].append(np.asarray(probability))
                gathered["entropy"].append(np.asarray(entropy))
                gathered["width"].append(float(crossover_width(temperatures, probability)))
                gathered["temp"].append(float(jnp.mean(predicted == test_temperature)))
                gathered["order"].append(float(jnp.mean(predicted == test_order)))
                gathered["trace"].append(np.asarray(trace))
            results["probability"][size, label] = np.stack(gathered["prob"])
            results["entropy"][size, label] = np.stack(gathered["entropy"])
            results["width"][size, label] = np.array(gathered["width"])
            results["accuracy_temperature"][size, label] = np.array(gathered["temp"])
            results["accuracy_order"][size, label] = np.array(gathered["order"])
            results["q_trace"][size, label] = np.stack(gathered["trace"])
            print(
                f"    {label:<16} accuracy: T-label {np.mean(gathered['temp']):.4f}"
                f"  order-parameter {np.mean(gathered['order']):.4f}"
                f"   final q {np.mean([t[-1] for t in gathered['trace']]):.3f}",
                flush=True,
            )

        print(
            f"    |m| threshold {float(threshold):.3f},"
            f" pooled label noise {results['bayes_error'][size]:.4f}",
            flush=True,
        )
        if size == sizes[-1]:
            for target in SHOWCASE_TEMPERATURES:
                index = int(jnp.argmin(jnp.abs(temperatures - target)))
                results["showcase"][target] = (
                    np.asarray(configurations[index, 0]),
                    float(jnp.abs(magnetization[index, 0])),
                    float(temperatures[index]),
                )
    return results


def learning_by_confusion(config: dict) -> dict:
    """Scan a *proposed* phase boundary; balanced accuracy peaks at the real one.

    The pipeline never sees ``T_c``: for each candidate ``T'`` the labels are
    ``1[T < T']``, the network is retrained, and its balanced test accuracy is
    recorded. A wrong boundary is inconsistent with the data on both sides, so the
    curve peaks at the true transition. This is the answer to "your labels already
    contain the answer".
    """
    size = config["sizes"][-1]
    temperatures = config["temperatures"]
    per_temperature = config["samples_per_temperature"]
    split = per_temperature - per_temperature // 2
    boundaries = np.linspace(2.0, 2.6, config["confusion_boundaries"])

    configurations = qp.sample_ising(
        jax.random.PRNGKey(1000 + size),
        size,
        temperatures,
        per_temperature,
        config["equilibration"][size],
    )
    steps = max(config["steps"] // 2, 100)

    curves = {}
    for label, q_fixed in CONFUSION_METHODS:
        accuracies = []
        for boundary in boundaries:
            train_x, train_y = flatten_symmetrized(
                configurations[:, :split], temperature_labels(temperatures, split, float(boundary))
            )
            test_x, test_y = flatten_symmetrized(
                configurations[:, split:],
                temperature_labels(temperatures, per_temperature - split, float(boundary)),
            )
            trained, _ = train(
                init_params(jax.random.PRNGKey(0), size**2),
                train_x,
                jax.nn.one_hot(train_y, 2),
                q_fixed,
                False,
                steps,
            )
            accuracies.append(
                balanced_accuracy(jnp.argmax(logits(trained, test_x), axis=-1), test_y)
            )
        curves[label] = np.array(accuracies)
        peak = float(qp.peak_temperature(jnp.asarray(boundaries), jnp.asarray(accuracies)))
        print(f"    confusion {label:<16} peak at T' = {peak:.4f}")
    return {"boundaries": boundaries, "curves": curves, "size": size}


# --------------------------------------------------------------------------- #
# Estimates of T_c and of the exponents
# --------------------------------------------------------------------------- #
def _crossings(results: dict, label: str, seed: int) -> jnp.ndarray:
    """Per-size temperature at which one seed's ``P(ordered)`` crosses 1/2."""
    temperatures = jnp.asarray(results["temperatures"])
    return jnp.array(
        [
            qp.crossing_temperature(temperatures, results["probability"][size, label][seed])
            for size in results["sizes"]
        ]
    )


def estimate_critical_temperatures(results: dict, confusion: dict) -> dict:
    """Every estimator's ``T_c``, with a seed standard error where one exists."""
    temperatures = jnp.asarray(results["temperatures"])
    sizes = jnp.asarray(results["sizes"], dtype=float)
    num_seeds = results["probability"][results["sizes"][0], BASELINE].shape[0]
    estimates: dict = {}

    def summarize(values: list[float]) -> tuple[float, float]:
        return float(np.mean(values)), float(np.std(values) / np.sqrt(max(len(values), 1)))

    for label, _, _ in METHODS:
        extrapolated, largest = [], []
        for seed in range(num_seeds):
            crossings = _crossings(results, label, seed)
            extrapolated.append(
                float(qp.finite_size_extrapolation(sizes, crossings, qp.ISING_NU)[0])
            )
            largest.append(float(crossings[-1]))
        estimates[f"{label}, $1/L \\to 0$"] = summarize(extrapolated)
        estimates[f"{label}, largest $L$"] = summarize(largest)

    # Label-free arm 1: the peak of the output Tsallis entropy, same extrapolation.
    peaks = []
    for seed in range(num_seeds):
        per_size = jnp.array(
            [
                qp.peak_temperature(temperatures, results["entropy"][size, INDICATOR][seed])
                for size in results["sizes"]
            ]
        )
        peaks.append(float(qp.finite_size_extrapolation(sizes, per_size, qp.ISING_NU)[0]))
    estimates["$S_q$ peak (label-free)"] = summarize(peaks)

    # Label-free arm 2: the confusion peak, refined parabolically.
    estimates["confusion peak (label-free)"] = (
        float(
            qp.peak_temperature(
                jnp.asarray(confusion["boundaries"]), jnp.asarray(confusion["curves"][INDICATOR])
            )
        ),
        0.0,
    )

    # Physics baseline 1: Binder-cumulant crossings against the smallest lattice.
    reference = jnp.asarray(results["binder"][results["sizes"][0]])
    crossings = jnp.array(
        [
            qp.crossing_temperature(
                *_windowed(temperatures, jnp.asarray(results["binder"][size]) - reference), 0.0
            )
            for size in results["sizes"][1:]
        ]
    )
    finite = crossings[jnp.isfinite(crossings)]
    estimates["Binder crossing (physics)"] = (float(jnp.mean(finite)), float(jnp.std(finite)))

    # Physics baseline 2: the inflection point of <|m|>(T).
    midpoints = 0.5 * (temperatures[1:] + temperatures[:-1])
    slopes = jnp.array(
        [
            qp.peak_temperature(
                *_windowed(
                    midpoints,
                    -jnp.diff(jnp.asarray(results["magnetization"][size])) / jnp.diff(temperatures),
                )
            )
            for size in results["sizes"]
        ]
    )
    estimates["$|m|$ inflection (physics)"] = (
        float(qp.finite_size_extrapolation(sizes, slopes, qp.ISING_NU)[0]),
        0.0,
    )
    return estimates


def critical_exponents(results: dict) -> dict:
    r"""Recover ``nu`` from the classifier's crossover width and ``beta`` from ``<|m|>``."""
    temperatures = jnp.asarray(results["temperatures"])
    sizes = jnp.asarray(results["sizes"], dtype=float)

    widths = jnp.array(
        [float(np.mean(results["width"][size, BASELINE])) for size in results["sizes"]]
    )
    # w(L) ~ L^{-1/nu}, so the log-log slope is -1/nu.
    slope, _, stderr = qp.fit_power_law(sizes, widths)
    nu = float(-1.0 / slope)

    # Right at T_c, <|m|> ~ L^{-beta/nu}: read beta off the size dependence.
    index = int(jnp.argmin(jnp.abs(temperatures - qp.ISING_TC)))
    at_criticality = jnp.array([results["magnetization"][size][index] for size in results["sizes"]])
    magnetization_slope, _, magnetization_error = qp.fit_power_law(sizes, at_criticality)
    return {
        "nu": (nu, float(stderr / slope**2)),
        "beta": (
            float(-magnetization_slope * qp.ISING_NU),
            float(magnetization_error * qp.ISING_NU),
        ),
        "widths": np.asarray(widths),
    }


