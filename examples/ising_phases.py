# (label, q_fixed, is_learnable). q = 1 is exactly the Carrasquilla-Melko setup.
BASELINE = "BGS (q = 1)"
METHODS = (
    (BASELINE, 1.0, False),
    ("Tsallis q = 0.7", 0.7, False),
    ("Tsallis q = 0.4", 0.4, False),
    ("learnable q", 0.0, True),
)
INDICATOR = "Tsallis q = 0.4"  # arm whose output supplies the label-free indicators

# Learnable-q range, matching examples/classification.py: it spans the robust
# (q < 1) and standard (q = 1) regimes and starts inside the robust one, since
# starting near q = 1 lets the network fit the contested band before q descends.
Q_MIN, Q_MAX, Q_RAW_INIT = 0.3, 1.3, -1.4  # init q ~ 0.50

HIDDEN = (64, 64)
LR = 3e-3
CONFUSION_METHODS = ((BASELINE, 1.0), ("Tsallis q = 0.4", 0.4))

# The two non-ML physics baselines are read inside the dense part of the
# temperature grid. This window contains the exact T_c, so those two estimators
# are told roughly where to look; it is applied to them and not to the learned
# estimators because restricting them *helps* them -- a noisy Binder curve
# crosses many times far from T_c -- which keeps the comparison conservative
# rather than flattering to the Tsallis arms. The confusion scan and the
# classifier crossings see the whole grid. Stated in the docs page too.
CRITICAL_WINDOW = (2.00, 2.62)

# Panel (a) shows one configuration from each phase and one at criticality.
SHOWCASE_TEMPERATURES = (1.5, qp.ISING_TC, 3.2)


def _temperature_grid(low: int, middle: int, high: int) -> jnp.ndarray:
    """A grid that is dense through the critical region and sparse outside it."""
    return jnp.concatenate(
        [
            jnp.linspace(1.20, 1.95, low),
            jnp.linspace(2.02, 2.58, middle),
            jnp.linspace(2.70, 3.60, high),
        ]
    )


