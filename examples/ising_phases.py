r"""Machine learning the 2-D Ising transition, with physically generated label noise.

Classifying Monte Carlo spin configurations as "ordered" or "disordered" and
reading the critical temperature off the classifier is the standard machine-
learning approach to phases of matter (Carrasquilla & Melko, 2017). The ``q = 1``
arm below *is* that method: an MLP trained with ordinary cross-entropy.

What makes this a Tsallis problem is where the labels come from. They are
assigned by temperature, ``y = 1[T < T_c]``, but near the transition the
correlation length ``xi ~ |T - T_c|^{-1}`` exceeds the lattice, so a
configuration drawn just *above* ``T_c`` is genuinely typical of the ordered
phase. Its temperature label is then wrong -- this is **label noise generated by
the physics of finite-size crossover**, not injected by hand as in
``examples/classification.py``. And because it is physical, it is *measurable*
and it has a *knob*: ``eta_eff(T, L)`` is the error an optimal ``|m|``-threshold
classifier makes against the temperature labels, and it shrinks as ``L`` grows
and the crossover narrows.

That gives a sharper question than "is Tsallis better": the bounded Tsallis
cross-entropy (``q < 1``, per-example loss at most ``1/(1-q)``) should help in
proportion to how much of this noise there is, and the lattice size sets that.

What the run measures, scored against the order parameter rather than against the
temperature labels (the physical analogue of a clean test set), is a **threshold
rather than a smooth trend**. Where the pooled noise exceeds roughly 13 %
(``L <= 10``), ``q = 0.4`` and the learnable ``q`` gain about one accuracy point
over ``q = 1``, several standard errors clear. Where it falls below roughly 11 %
(``L >= 12``), they *cost* about the same. So nonextensivity pays here only above
a measurable value of a physical parameter -- and we report the sign change
rather than smoothing it over.

The learnable ``q`` is the arm that survives the regime change: it is at or near
the top in the noisy regime and the least penalized in the clean one. That is the
practical argument for treating ``q`` as a parameter to be learned rather than a
constant to be chosen, in a setting where the right value depends on a physical
scale the modeller does not control.

Every number is checked against something exact, so all of this is measurement
rather than claim:

- ``T_c = 2/ln(1+sqrt 2) = 2.2691853`` (Onsager, 1944), and the exact exponents
  ``nu = 1``, ``beta = 1/8``, ``u(T_c) = -sqrt 2 J``.
- The sampler is validated against Onsager's ``m(T)`` and against exhaustive
  enumeration of all ``2**16`` states at ``L = 4``.
- Two *non*-machine-learning physics baselines locate ``T_c`` for comparison:
  the Binder-cumulant crossing and the ``<|m|>`` inflection point.
- Two *label-free* indicators answer the objection that the labels already encode
  ``T_c``: the Tsallis entropy of the network's output, whose peak needs no
  ``T_c``, and learning by confusion (van Nieuwenburg et al., 2017), which scans
  a *proposed* boundary and never sees the true one.

Run with: ``uv run python examples/ising_phases.py``
Add ``--full`` (or set ``QJAX_FULL=1``) for the large-lattice configuration.
"""

