def plot_main(results: dict, exponents: dict, path: Path) -> None:
    """Configurations, sampler validation, the measured noise, and what q buys."""
    temperatures = results["temperatures"]
    sizes = results["sizes"]
    size_colors = qcolors(len(sizes))
    method_colors = qcolors(len(METHODS))
    method_styles = qlinestyles(len(METHODS))

    fig = plt.figure(figsize=(13.2, 7.6))
    grid = fig.add_gridspec(2, 3, hspace=0.36, wspace=0.30)

    # (a) three configurations spanning the transition.
    inner = grid[0, 0].subgridspec(1, 3, wspace=0.08)
    for column, target in enumerate(SHOWCASE_TEMPERATURES):
        spins, absolute, actual = results["showcase"][target]
        ax = fig.add_subplot(inner[0, column])
        ax.imshow(spins, cmap=CMAP, vmin=-1, vmax=1, interpolation="nearest")
        ax.set_xticks([])
        ax.set_yticks([])
        ax.set_title(f"$T={actual:.2f}$\n$|m|={absolute:.2f}$", fontsize=8.5, pad=3)
        if column == 1:
            ax.set_xlabel(f"(a)  $L={sizes[-1]}$ configurations", fontsize=9.5, labelpad=4)

    # (b) sampler validation against Onsager and the exact L = 4 enumeration.
    ax = fig.add_subplot(grid[0, 1])
    fine = np.linspace(temperatures.min(), qp.ISING_TC, 300)
    ax.plot(
        fine,
        np.asarray(qp.onsager_magnetization(jnp.asarray(fine))),
        color="0.25",
        lw=1.2,
        ls="--",
        label=r"Onsager $m(T)$, $L\to\infty$",
    )
    for color, size in zip(size_colors, sizes, strict=True):
        ax.plot(
            temperatures, results["magnetization"][size], color=color, lw=1.3, label=f"$L={size}$"
        )
    # The L = 4 pair is the actual validation: a sampled curve on top of the
    # exhaustive enumeration of all 2**16 states, at the same lattice size.
    exact = jax.vmap(lambda t: qp.ising_exact_observables(4, t)["abs_magnetization"])(
        jnp.asarray(temperatures)
    )
    sampled = qp.sample_ising(jax.random.PRNGKey(4), 4, jnp.asarray(temperatures), 2000, 200)
    ax.plot(
        temperatures,
        np.asarray(jnp.mean(jnp.abs(qp.ising_magnetization(sampled)), axis=-1)),
        color="0.45",
        lw=1.0,
        label="sampled $L=4$",
    )
    ax.plot(
        temperatures,
        np.asarray(exact),
        ls="none",
        marker="o",
        ms=3.2,
        mfc="none",
        mew=0.8,
        color="0.15",
        label=r"exact $L=4$ ($2^{16}$ states)",
    )
    ax.axvline(qp.ISING_TC, color="0.55", lw=0.9, ls=":")
    ax.set_xlabel("temperature $T$")
    ax.set_ylabel(r"$\langle |m| \rangle$")
    ax.set_title("(b) sampler vs. exact", fontsize=10)
    ax.legend(fontsize=7.4, ncols=2, loc="lower left")

    # (c) the measured, physically generated label noise.
    ax = fig.add_subplot(grid[0, 2])
    for color, size in zip(size_colors, sizes, strict=True):
        ax.plot(
            temperatures,
            results["noise"][size],
            color=color,
            lw=1.4,
            label=rf"$L={size}$  ($\bar\eta={results['bayes_error'][size]:.3f}$)",
        )
    ax.axvline(qp.ISING_TC, color="0.55", lw=0.9, ls=":")
    ax.set_xlabel("temperature $T$")
    ax.set_ylabel(r"$\eta_{\rm eff}(T, L)$")
    ax.set_title("(c) label noise from finite-size crossover", fontsize=10)
    ax.legend(fontsize=7.4)

    # (d) P(ordered) per arm at the largest lattice.
    ax = fig.add_subplot(grid[1, 0])
    largest = sizes[-1]
    for color, style, (label, _, _) in zip(method_colors, method_styles, METHODS, strict=True):
        curves = results["probability"][largest, label]
        mean = curves.mean(axis=0)
        ax.plot(temperatures, mean, color=color, ls=style, lw=1.5, label=label)
        if curves.shape[0] > 1:
            spread = curves.std(axis=0) / np.sqrt(curves.shape[0])
            ax.fill_between(
                temperatures, mean - spread, mean + spread, color=color, alpha=0.18, lw=0
            )
    ax.axhline(0.5, color="0.55", lw=0.8)
    ax.axvline(qp.ISING_TC, color="0.25", lw=1.0, ls="--", label="exact $T_c$")
    ax.set_xlabel("temperature $T$")
    ax.set_ylabel(r"$\langle P(\mathrm{ordered}) \rangle$")
    ax.set_title(f"(d) classifier output, $L={largest}$", fontsize=10)
    ax.legend(fontsize=8)

    # (e) finite-size extrapolation of the 1/2 crossing.
    ax = fig.add_subplot(grid[1, 1])
    inverse = 1.0 / np.asarray(sizes, dtype=float)
    for color, style, (label, _, _) in zip(method_colors, method_styles, METHODS, strict=True):
        crossings = np.array(
            [
                float(
                    qp.crossing_temperature(
                        jnp.asarray(temperatures),
                        jnp.asarray(results["probability"][size, label].mean(axis=0)),
                    )
                )
                for size in sizes
            ]
        )
        intercept, slope, _ = qp.finite_size_extrapolation(
            jnp.asarray(sizes, dtype=float), jnp.asarray(crossings), qp.ISING_NU
        )
        ax.plot(inverse, crossings, ls="none", marker="o", ms=4.5, color=color)
        span = np.linspace(0.0, inverse.max() * 1.05, 20)
        ax.plot(
            span,
            float(intercept) + float(slope) * span,
            color=color,
            ls=style,
            lw=1.3,
            label=f"{label}: {float(intercept):.4f}",
        )
    ax.axhline(qp.ISING_TC, color="0.25", lw=1.0, ls="--")
    ax.text(
        0.02,
        qp.ISING_TC,
        f"  exact {qp.ISING_TC:.4f}",
        va="bottom",
        ha="left",
        fontsize=8,
        color="0.25",
        transform=ax.get_yaxis_transform(),
    )
    ax.set_xlabel("$1/L$")
    ax.set_ylabel(r"$T_c(L)$")
    ax.set_title(r"(e) extrapolation with exact $\nu = 1$", fontsize=10)
    largest_crossing = float(
        qp.crossing_temperature(
            jnp.asarray(temperatures),
            jnp.asarray(results["probability"][sizes[-1], BASELINE].mean(axis=0)),
        )
    )
    ax.annotate(
        f"crossing at $L={sizes[-1]}$: {largest_crossing:.4f}\n"
        r"(the $1/L$ fit curves at small $L$)",
        (0.03, 0.03),
        xycoords="axes fraction",
        fontsize=7.2,
        color="0.3",
    )
    ax.legend(fontsize=7.6, loc="upper right")

    # (f) the Tsallis result: the gain tracks the physically generated noise.
    ax = fig.add_subplot(grid[1, 2])
    noise = np.array([results["bayes_error"][size] for size in sizes])
    baseline = np.array([results["accuracy_order"][size, BASELINE].mean() for size in sizes])
    for color, style, (label, _, _) in zip(method_colors, method_styles, METHODS, strict=True):
        if label == BASELINE:
            continue
        arm = np.array([results["accuracy_order"][size, label] for size in sizes])
        gain = 100.0 * (arm.mean(axis=1) - baseline)
        spread = 100.0 * arm.std(axis=1) / np.sqrt(arm.shape[1])
        ax.errorbar(
            noise,
            gain,
            yerr=spread,
            color=color,
            ls=style,
            lw=1.5,
            marker="o",
            ms=4.5,
            capsize=2,
            label=label,
        )
    ax.axhline(0.0, color="0.25", lw=1.0, ls="--")
    margin = 0.06 * (noise.max() - noise.min())
    ax.set_xlim(noise.min() - margin, noise.max() + margin)
    top = ax.get_ylim()[1]
    for x, size in zip(noise, sizes, strict=True):
        ax.annotate(f"$L={size}$", (x, top), fontsize=7, ha="center", va="top", color="0.35")
    ax.set_xlabel(r"pooled label noise $\bar\eta(L)$")
    ax.set_ylabel("order-parameter accuracy\ngain over BGS (points)")
    ax.set_title(r"(f) what $q<1$ buys, vs. how much noise there is", fontsize=10)
    ax.legend(fontsize=7.6, loc="upper left")

    save_figure(fig, path)
    plt.close(fig)


def plot_scaling(results: dict, exponents: dict, estimates: dict, confusion: dict, path: Path):
    """Binder, the FSS collapse, the confusion scan, and the ``T_c`` scoreboard."""
    temperatures = results["temperatures"]
    sizes = results["sizes"]
    size_colors = qcolors(len(sizes))

    fig, axes = plt.subplots(2, 2, figsize=(11.8, 8.4))
    fig.subplots_adjust(hspace=0.34, wspace=0.40)

    # (a) Binder cumulant: curves for different L cross at T_c.
    ax = axes[0, 0]
    for color, size in zip(size_colors, sizes, strict=True):
        ax.plot(temperatures, results["binder"][size], color=color, lw=1.4, label=f"$L={size}$")
    ax.axvline(qp.ISING_TC, color="0.25", lw=1.0, ls="--", label="exact $T_c$")
    ax.axhline(2.0 / 3.0, color="0.6", lw=0.7, ls=":")
    ax.set_xlabel("temperature $T$")
    ax.set_ylabel(r"$U_4$")
    ax.set_title("(a) Binder cumulant (no machine learning)", fontsize=10)
    ax.legend(fontsize=8, loc="lower left")

    # (b) FSS collapse with the exact exponents: a strong equilibration check.
    ax = axes[0, 1]
    for color, size in zip(size_colors, sizes, strict=True):
        scaled_x = (temperatures - qp.ISING_TC) * size ** (1.0 / qp.ISING_NU)
        scaled_y = results["magnetization"][size] * size ** (qp.ISING_BETA_EXP / qp.ISING_NU)
        ax.plot(scaled_x, scaled_y, color=color, lw=1.3, marker="o", ms=2.5, label=f"$L={size}$")
    ax.set_xlim(-25.0, 25.0)
    ax.set_xlabel(r"$(T - T_c)\,L^{1/\nu}$")
    ax.set_ylabel(r"$\langle |m| \rangle\, L^{\beta/\nu}$")
    ax.set_title(r"(b) collapse at exact $\beta=1/8$, $\nu=1$", fontsize=10)
    ax.legend(fontsize=8)

    # Inset: nu from the classifier's own crossover width, no extrapolation.
    widths = exponents["widths"]
    inset = ax.inset_axes((0.09, 0.11, 0.33, 0.30))
    inset.loglog(sizes, widths, "o", ms=3.5, color=size_colors[-1])
    fitted = np.asarray(sizes, dtype=float)
    nu = exponents["nu"][0]
    inset.loglog(fitted, widths[0] * (fitted / fitted[0]) ** (-1.0 / nu), lw=1.0, color="0.35")
    inset.set_title(rf"$w \sim L^{{-1/\nu}}$: $\nu={nu:.2f}$", fontsize=7, pad=2)
    inset.set_xlabel("$L$", fontsize=6.5, labelpad=0)
    inset.set_ylabel("$w$", fontsize=6.5, labelpad=0)
    inset.tick_params(labelsize=5.5, which="both")
    inset.grid(visible=False)

    # (c) learning by confusion: the peak needs no knowledge of T_c.
    ax = axes[1, 0]
    for color, (label, _) in zip(qcolors(len(CONFUSION_METHODS)), CONFUSION_METHODS, strict=True):
        curve = confusion["curves"][label]
        ax.plot(confusion["boundaries"], curve, color=color, lw=1.5, marker="o", ms=4, label=label)
        ax.axvline(
            float(qp.peak_temperature(jnp.asarray(confusion["boundaries"]), jnp.asarray(curve))),
            color=color,
            lw=0.8,
            ls=":",
        )
    ax.axvline(qp.ISING_TC, color="0.25", lw=1.0, ls="--", label="exact $T_c$")
    ax.set_xlabel(r"proposed boundary $T'$")
    ax.set_ylabel("balanced test accuracy")
    ax.set_title(f"(c) learning by confusion, $L={confusion['size']}$", fontsize=10)
    ax.legend(fontsize=8)

    # (d) the scoreboard: |T_c estimate - exact| for every estimator.
    ax = axes[1, 1]
    keys = sorted(estimates, key=lambda k: abs(estimates[k][0] - qp.ISING_TC), reverse=True)
    errors = [abs(estimates[k][0] - qp.ISING_TC) for k in keys]
    spreads = [estimates[k][1] for k in keys]
    positions = np.arange(len(keys))
    colors = [
        "#1a759f" if "physics" in k else "#52b69a" if "free" in k else "#168aad" for k in keys
    ]
    ax.barh(positions, errors, xerr=spreads, color=colors, height=0.66, error_kw={"lw": 0.9})
    for y, (error, key) in enumerate(zip(errors, keys, strict=True)):
        ax.text(error + max(errors) * 0.02, y, f"{estimates[key][0]:.4f}", va="center", fontsize=7)
    ax.set_yticks(positions)
    ax.set_yticklabels(keys, fontsize=7.4)
    ax.set_xlabel(r"$|T_c^{\rm est} - 2.269185|$")
    ax.set_title("(d) distance from the exact $T_c$", fontsize=10)
    ax.grid(axis="y", visible=False)

    save_figure(fig, path)
    plt.close(fig)


